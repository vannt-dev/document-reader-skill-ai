"""Text extraction for HTML pages (.html, .htm), such as Confluence or wiki exports.

Standard library only. Read-only: no script runs, no stylesheet, image or link
is fetched. Navigation, scripts and styles are dropped; headings, paragraphs,
list items and table rows come out in document order, in the same shape as the
Word reader, so sections, outlines and citations work the same way.
"""

from __future__ import annotations

import re
from html.parser import HTMLParser
from pathlib import Path

from common import decode_text

# An HTML file larger than this is refused rather than read into memory.
MAX_HTML_BYTES = 64 * 1024 * 1024

# Elements whose content is never text a reader should see.
SKIPPED_TAGS = {
    "script", "style", "noscript", "template", "svg", "math", "canvas",
    "iframe", "object", "embed", "nav", "select", "button", "head",
}
# Page chrome that wiki exports put around the content: Confluence's
# breadcrumbs and "Document generated by Confluence" footer.
SKIPPED_IDS = {"breadcrumb-section", "breadcrumbs", "footer"}
SKIPPED_ROLES = {"navigation", "search", "banner", "contentinfo"}
VOID_TAGS = {
    "area", "base", "br", "col", "embed", "hr", "img", "input", "link",
    "meta", "param", "source", "track", "wbr",
}
# Starting or ending one of these ends the paragraph being collected.
BLOCK_TAGS = {
    "address", "article", "aside", "blockquote", "body", "caption", "dd", "details",
    "div", "dl", "dt", "fieldset", "figcaption", "figure", "footer", "form",
    "h1", "h2", "h3", "h4", "h5", "h6", "header", "hr", "html", "li", "main",
    "ol", "p", "pre", "section", "summary", "table", "tbody", "td", "tfoot",
    "th", "thead", "tr", "ul",
}
HEADING_TAG = re.compile(r"^h([1-6])$")
META_CHARSET = re.compile(rb"""<meta[^>]+charset\s*=\s*["']?\s*([A-Za-z0-9_.:-]+)""", re.IGNORECASE)
SPACES = re.compile(r"\s+")


class _Extractor(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.items: list[dict] = []
        self.title: str | None = None
        self._stack: list[tuple[str, bool]] = []  # (tag, skips its content)
        self._skipping = 0
        self._in_title = False
        self._title_parts: list[str] = []
        self._buffer: list[str] = []
        self._heading: int | None = None
        self._pre = 0
        self._lists: list[dict] = []  # {"ordered": bool, "count": int}
        self._prefix = ""
        self._rows: list[list[str] | None] = []  # one entry per open table
        self._cell: list[str] | None = None
        self._cells_stack: list[list[str] | None] = []

    # --- collecting text ---------------------------------------------------

    def _flush(self) -> None:
        raw = "".join(self._buffer)
        self._buffer = []
        if self._pre:
            text = "\n".join(line.rstrip() for line in raw.strip("\n").splitlines())
        else:
            text = SPACES.sub(" ", raw).strip()
        if not text:
            return
        if self._cell is not None:
            self._cell.append(text)
            return
        if self._heading:
            self.items.append({"kind": "heading", "level": self._heading, "text": text})
        else:
            self.items.append({"kind": "paragraph", "level": None, "text": self._prefix + text})
            # A list item's marker goes on its first line only.
            if self._prefix:
                self._prefix = " " * len(self._prefix)

    def _start_cell(self) -> None:
        self._flush()
        self._cell = []

    def _end_cell(self) -> None:
        if self._cell is None:
            return
        self._flush()
        row = self._rows[-1] if self._rows else None
        if row is not None:
            row.append(" ".join(self._cell))
        self._cell = None

    def _end_row(self) -> None:
        self._end_cell()
        if self._rows and self._rows[-1] is not None:
            cells = self._rows[-1]
            if any(cells):
                self.items.append({"kind": "table_row", "level": None, "text": " | ".join(cells)})
            self._rows[-1] = None

    # --- parser callbacks ----------------------------------------------------

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        values = dict(attrs)
        if tag == "title":
            # The page title sits in <head>, which is skipped; keep it apart.
            self._in_title = True
            return
        if tag in VOID_TAGS:
            if tag in {"br", "hr"} and not self._skipping:
                if self._pre and tag == "br":
                    self._buffer.append("\n")
                else:
                    self._flush()
            return
        skips = (
            tag in SKIPPED_TAGS
            or (values.get("id") or "").casefold() in SKIPPED_IDS
            or (values.get("role") or "").casefold() in SKIPPED_ROLES
            or "hidden" in values
            or (values.get("aria-hidden") or "").casefold() == "true"
        )
        self._stack.append((tag, skips))
        if skips:
            self._skipping += 1
        if self._skipping:
            return
        self._open(tag)

    def _open(self, tag: str) -> None:
        if tag in BLOCK_TAGS and tag not in {"td", "th"}:
            self._flush()
        if match := HEADING_TAG.match(tag):
            self._heading = int(match.group(1))
        elif tag == "pre":
            self._pre += 1
        elif tag in {"ul", "ol"}:
            self._lists.append({"ordered": tag == "ol", "count": 0})
        elif tag == "li":
            depth = max(len(self._lists), 1)
            if self._lists and self._lists[-1]["ordered"]:
                self._lists[-1]["count"] += 1
                marker = f"{self._lists[-1]['count']}. "
            else:
                marker = "- "
            self._prefix = "  " * (depth - 1) + marker
        elif tag == "table":
            self._cells_stack.append(self._cell)
            self._cell = None
            self._rows.append(None)
        elif tag == "tr":
            self._end_row()
            if self._rows:
                self._rows[-1] = []
        elif tag in {"td", "th"}:
            self._end_cell()
            if self._rows and self._rows[-1] is None:
                self._rows[-1] = []  # a cell without its <tr>
            self._start_cell()

    def handle_endtag(self, tag: str) -> None:
        if tag == "title" and self._in_title:
            self._in_title = False
            if self.title is None:  # an <svg> has <title> elements of its own
                self.title = SPACES.sub(" ", "".join(self._title_parts)).strip() or None
            self._title_parts = []
            return
        if tag in VOID_TAGS or not any(open_tag == tag for open_tag, _ in self._stack):
            return  # a stray end tag closes nothing
        # Close everything opened inside it too: <li> and <p> often have no end tag.
        while self._stack:
            open_tag, skips = self._stack.pop()
            if not self._skipping:
                self._close(open_tag)
            if skips:
                self._skipping -= 1
            if open_tag == tag:
                break

    def _close(self, tag: str) -> None:
        if tag in {"td", "th"}:
            self._end_cell()
            return
        if tag == "tr":
            self._end_row()
            return
        if tag in BLOCK_TAGS:
            self._flush()
        if HEADING_TAG.match(tag):
            self._heading = None
        elif tag == "pre":
            self._pre = max(self._pre - 1, 0)
        elif tag in {"ul", "ol"}:
            if self._lists:
                self._lists.pop()
            self._prefix = ""
        elif tag == "li":
            self._prefix = ""
        elif tag == "table":
            self._end_row()
            if self._rows:
                self._rows.pop()
            self._cell = self._cells_stack.pop() if self._cells_stack else None

    def handle_data(self, data: str) -> None:
        if self._in_title:
            self._title_parts.append(data)
        elif not self._skipping:
            self._buffer.append(data)

    def close(self) -> None:
        super().close()
        while self._stack:
            tag, skips = self._stack.pop()
            if not self._skipping:
                self._close(tag)
            if skips:
                self._skipping -= 1
        self._flush()


def html_decode(data: bytes) -> tuple[str, str]:
    """Text and encoding of an HTML file, honouring its <meta charset>."""
    declared = META_CHARSET.search(data[:4096])
    return decode_text(data, declared.group(1).decode("ascii") if declared else None)


def html_document(path: Path) -> dict:
    """{"title", "encoding", "items"}; items are numbered from 1 like .docx paragraphs."""
    if path.stat().st_size > MAX_HTML_BYTES:
        raise ValueError(f"HTML file is larger than {MAX_HTML_BYTES // (1024 * 1024)} MB; refusing to read it")
    text, encoding = html_decode(path.read_bytes())
    parser = _Extractor()
    parser.feed(text)
    parser.close()
    for index, item in enumerate(parser.items, 1):
        item["index"] = index
    return {"title": parser.title, "encoding": encoding, "items": parser.items}


def html_items(path: Path) -> list[dict]:
    return html_document(path)["items"]
