# --- encoding detection ------------------------------------------------------


@pytest.mark.parametrize(
    "data, encoding",
    [
        ("Thanh toán".encode("utf-8"), "utf-8"),
        (b"\xef\xbb\xbf" + "Thanh toán".encode("utf-8"), "utf-8"),
        (b"\xff\xfe" + "Thanh toán".encode("utf-16-le"), "utf-16-le"),
        (b"\xfe\xff" + "Thanh toán".encode("utf-16-be"), "utf-16-be"),
        ("Thanh toán".encode("utf-16-le"), "utf-16-le"),
    ],
)
def test_decode_text_detects_the_encoding(data, encoding):
    assert common.decode_text(data) == ("Thanh toán", encoding)


def test_decode_text_falls_back_to_windows_1252_and_never_fails():
    assert common.decode_text("Montréal".encode("cp1252")) == ("Montréal", "cp1252")
    # Bytes that are not valid in any of them still read.
    text, encoding = common.decode_text(b"caf\xe9 \x81")
    assert encoding == "cp1252" and text.startswith("café")


def test_decode_text_honours_a_declared_encoding_but_not_a_wrong_one():
    assert common.decode_text("Montréal".encode("cp1252"), "windows-1252")[0] == "Montréal"
    assert common.decode_text("Montréal".encode("utf-8"), "no-such-codec") == ("Montréal", "utf-8")
    assert common.decode_text("Montréal".encode("utf-8"), "ascii") == ("Montréal", "utf-8")


# --- .txt --------------------------------------------------------------------


def test_read_txt_outline_heading_and_lines(sample_txt):
    outline = read_txt.outline(sample_txt)
    assert (outline["type"], outline["encoding"], outline["line_count"]) == ("text", "utf-8", 7)
    assert [item["title"] for item in outline["outline"]] == ["Decisions", "Open questions"]

    section = read_txt.read(sample_txt, "decisions", None, None, 12000)
    assert section["content"] == "# Decisions\nREQ-201 Export to CSV.\n"
    assert section["source"]["start_line"] == 3 and section["source"]["end_line"] == 5

    lines = read_txt.read(sample_txt, None, 1, 1, 12000)
    assert lines["content"] == "Meeting notes, 3 Oct"
    assert read_txt.read(sample_txt, None, None, None, 5)["truncated"] is True
    with pytest.raises(ValueError, match="Heading not found"):
        read_txt.read(sample_txt, "Nope", None, None, 100)


def test_read_txt_reads_a_utf16_file_from_notepad(tmp_path):
    path = tmp_path / "unicode.txt"
    path.write_bytes(b"\xff\xfe" + "Yêu cầu\r\nĐăng nhập\r\n".encode("utf-16-le"))

    result = read_txt.read(path, None, None, None, 100)
    assert result["encoding"] == "utf-16-le"
    assert result["content"] == "Yêu cầu\nĐăng nhập"


def test_txt_sections_cut_a_file_without_headings_into_windows():
    lines = [f"line {number}" for number in range(1, 8)]
    pieces = read_txt.sections(lines, 3)
    assert [(piece["title"], piece["start"], piece["end"]) for piece in pieces] == [
        (None, 1, 3), (None, 4, 6), (None, 7, 7),
    ]


# --- .html -------------------------------------------------------------------


def test_html_keeps_the_content_and_drops_scripts_styles_and_navigation(sample_html):
    page = html_text.html_document(sample_html)
    texts = [item["text"] for item in page["items"]]

    assert page["title"] == "Payments : Checkout rules"
    assert page["encoding"] == "utf-8"
    assert texts[0] == "Checkout rules"
    joined = "\n".join(texts)
    for dropped in ("do-not-read", "never", "font-family", "Space navigation",
                    "Document generated by Confluence", "Hidden note"):
        assert dropped not in joined
    # Breadcrumbs repeat the space name; only the title should be read.
    assert "Payments" not in joined


def test_html_turns_headings_lists_and_tables_into_text_structure(sample_html):
    items = html_text.html_items(sample_html)
    by_text = {item["text"]: item for item in items}

    assert [(item["level"], item["text"]) for item in items if item["kind"] == "heading"] == [
        (1, "Checkout rules"), (2, "Limits"), (2, "Fees"),
    ]
    assert by_text["Rules for the checkout page & its API."]["kind"] == "paragraph"
    order = [item["text"] for item in items if item["kind"] == "paragraph"]
    assert order[order.index("- REQ-101 A cart holds at most 50 items."):][:6] == [
        "- REQ-101 A cart holds at most 50 items.",
        "- Payment methods:",
        "  - Card",
        "  - Bank transfer",
        "1. First step",
        "2. Second step",
    ]
    assert [item["text"] for item in items if item["kind"] == "table_row"] == [
        "ID | Fee", "REQ-102 | 2% for cards",
    ]
    assert "code line 1\n    indented line 2" in by_text
    assert [item["index"] for item in items] == list(range(1, len(items) + 1))


def test_html_survives_unclosed_tags_and_stray_end_tags(tmp_path):
    path = tmp_path / "sloppy.htm"
    path.write_bytes(
        b"<h1>Rules</h1><p>First<p>Second</div>"
        b"<ul><li>One<li>Two</ul><table><tr><td>A<td>B<tr><td>C</table><p>After"
    )

    texts = [item["text"] for item in html_text.html_items(path)]
    assert texts == ["Rules", "First", "Second", "- One", "- Two", "A | B", "C", "After"]


def test_html_honours_meta_charset(tmp_path):
    path = tmp_path / "legacy.html"
    path.write_bytes(
        b'<html><head><meta charset="windows-1252"></head><body><p>Montr\xe9al</p></body></html>'
    )

    page = html_text.html_document(path)
    assert page["encoding"] == "windows-1252"
    assert page["items"][0]["text"] == "Montréal"


def test_read_html_outline_and_heading(sample_html):
    outline = read_html.outline(sample_html)
    assert outline["title"] == "Payments : Checkout rules"
    assert outline["table_rows"] == 2
    assert [entry["title"] for entry in outline["outline"]] == ["Checkout rules", "Limits", "Fees"]

    fees = read_html.read(sample_html, "fees", None, None, 12000)
    assert fees["content"].splitlines()[:2] == ["## Fees", "1. First step"]
    assert "REQ-102 | 2% for cards" in fees["content"]
    assert "Card" not in fees["content"]

    # The top heading's section takes in its sub-headings.
    whole = read_html.read(sample_html, "Checkout rules", None, None, 12000)
    assert whole["source"]["end_paragraph"] == outline["paragraph_count"]


# --- index, cache, search ----------------------------------------------------


def test_index_documents_records_txt_and_html(tmp_path, sample_txt, sample_html):
    output = tmp_path / "manifest.json"
    subprocess.run(
        [sys.executable, str(SCRIPTS / "index_documents.py"), str(tmp_path), "--output", str(output)],
        check=True,
    )
    manifest = json.loads(output.read_text(encoding="utf-8"))
    documents = {document["path"]: document for document in manifest["documents"]}

    assert documents["notes.txt"]["type"] == "text"
    assert documents["notes.txt"]["structure"]["encoding"] == "utf-8"
    assert [h["title"] for h in documents["notes.txt"]["structure"]["headings"]] == ["Decisions", "Open questions"]
    assert documents["checkout.html"]["type"] == "html"
    assert documents["checkout.html"]["structure"]["title"] == "Payments : Checkout rules"
    assert {".txt", ".html", ".htm"} <= set(manifest["supported_extensions"])


def test_build_and_query_cache_for_txt_and_html(tmp_path, sample_txt, sample_html, manifest_for):
    cache_dir = tmp_path / ".document-reader"
    manifest_path = manifest_for([sample_txt, sample_html], cache_dir)
    index = build_cache.build(manifest_path, cache_dir, window=500)

    blocks = {document["doc_id"]: document["blocks"] for document in index["documents"]}
    assert [block["label"] for block in blocks["notes-txt"]] == ["(preamble)", "Decisions", "Open questions"]
    assert [block["label"] for block in blocks["checkout-html"]] == ["Checkout rules", "Limits", "Fees"]
    assert not any("error" in document for document in index["documents"])

    hits = query_cache.query(cache_dir, keyword="REQ-102")["results"]
    assert [(hit["doc_id"], hit["label"]) for hit in hits] == [("checkout-html", "Fees")]
    assert hits[0]["ref"]["paragraphs"] == [9, 14]

    hits = query_cache.query(cache_dir, keyword="export to csv")["results"]
    assert hits[0]["ref"] == {"heading": "Decisions", "level": 1, "lines": [3, 5]}


def test_search_document_cites_txt_lines_and_html_paragraphs(sample_txt, sample_html):
    def search(path, query):
        completed = subprocess.run(
            [sys.executable, str(SCRIPTS / "search_document.py"), str(path), query],
            check=True, capture_output=True, text=True, encoding="utf-8",
        )
        return json.loads(completed.stdout)

    txt = search(sample_txt, "REQ-201")
    assert txt["type"] == "text"
    assert txt["matches"][0]["line"] == 4

    html = search(sample_html, "bank transfer")
    assert html["type"] == "html"
    assert html["matches"][0]["paragraph"] == 8
    assert "do-not-read" not in json.dumps(search(sample_html, "a"))
